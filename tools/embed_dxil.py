#!/usr/bin/env python3
"""Embeds the path tracer's compiled shaders (DXIL, from the Windows SDK's
dxc.exe; tools/windows_build.py) in the D3D12 renderer as C data:

    python tools/embed_dxil.py OUTPUT.c SHADER.dxil...

writes OUTPUT.c with, for each SHADER.dxil, `renderer_dxil_<name>` (its
bytes) and `renderer_dxil_<name>_size`, as port/windows/renderer/renderer.h
declares them.
"""

import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    output = Path(sys.argv[1])
    lines = ["/* generated by tools/embed_dxil.py: the path tracer's shaders */", "", "#include <stddef.h>", ""]
    for path in map(Path, sys.argv[2:]):
        name = path.stem
        data = path.read_bytes()
        lines.append(f"const unsigned char renderer_dxil_{name}[] =")
        lines.append("{")
        for start in range(0, len(data), 24):
            lines.append("\t" + ", ".join(str(byte) for byte in data[start:start + 24]) + ",")
        lines.append("};")
        lines.append(f"const size_t renderer_dxil_{name}_size = {len(data)};")
        lines.append("")
    text = "\n".join(lines)
    # (unchanged output leaves the file's time alone: ninja's restat)
    if not output.exists() or output.read_text() != text:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
